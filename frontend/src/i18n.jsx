const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      const saved = window.localStorage.getItem("suchnasetu-language");
      return languageOptions.some((option) => option.id === saved) ? saved : "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    try {
      window.localStorage.setItem("suchnasetu-language", language);
    } catch {
      // Language selection remains available for the current session if storage is disabled.
    }
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t(key, parameters = {}) {
      const template = translations[language][key] || translations.en[key] || key;
      return template.replace(/\{(\w+)\}/g, (_match, name) => parameters[name] ?? `{${name}}`);
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within a LanguageProvider.");
  return context;
}

export function withLanguageInstruction(query, language) {
  if (language === "hi") {
    return `कृपया हिंदी में उत्तर दें। सरकारी योजनाओं और उनके आधिकारिक नामों को सही रखें।\n\n${query}`;
  }
  if (language === "gu") {
    return `કૃપા કરીને ગુજરાતીમાં જવાબ આપો. સરકારી યોજનાઓ અને તેમના સત્તાવાર નામ સાચા રાખો.\n\n${query}`;
  }
  return query;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className="language-switcher">
      <span>{t("language.label")}</span>
      <select aria-label={t("language.label")} value={language} onChange={(event) => setLanguage(event.target.value)}>
        {languageOptions.map((option) => <option key={option.id} value={option.id}>{option.label}</option>)}
      </select>
    </label>
  );
}
